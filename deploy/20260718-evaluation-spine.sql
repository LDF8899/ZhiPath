  `goal` varchar(240) NULL,
  `attempt_status` enum('started','graded','committed','failed') NOT NULL DEFAULT 'started',
  `rubric_key` varchar(120) NOT NULL DEFAULT 'default_skill_v1',
  `rubric_version` varchar(40) NOT NULL DEFAULT '1.0.0',

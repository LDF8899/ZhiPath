CREATE TABLE IF NOT EXISTS `evaluation_rubrics_v3` (
  `status` tinyint NOT NULL DEFAULT 1,
  `id` bigint NOT NULL AUTO_INCREMENT,
  `create_time` bigint NULL,
  `update_time` bigint NULL,
  `rubric_key` varchar(120) NOT NULL,
  `name` varchar(160) NOT NULL,
  `version` varchar(40) NOT NULL DEFAULT '1.0.0',
  `target_type` enum('skill','radar_dimension','job_match','learning_action','project') NOT NULL DEFAULT 'skill',
  `pass_score` int NOT NULL DEFAULT 70,
  `dimensions_json` json NULL,
  `weights_json` json NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_evaluation_rubric_key_version` (`rubric_key`, `version`)
